package io.github.west3436.expedition.planet;

import io.github.west3436.expedition.ExpeditionMod;
import io.github.west3436.expedition.worldgen.PlanetChunkGenerator;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.dimension.LevelStem;

/**
 * Which dimensions Minecraft should count as stable, so a world with Expedition's never asks to be
 * backed up as one using "Experimental Settings".
 *
 * <p>Vanilla calls a world's settings experimental when it has any dimension besides the Overworld,
 * the Nether and the End, or one of those three with a generator other than vanilla's. That is
 * meant to warn about hand-edited world generation that a later version may not load. Expedition's
 * dimensions are not that: they are part of the mod, and are saved and loaded like any other. So
 * these count as vanilla-like:
 *
 * <ul>
 *   <li>every dimension in the {@code expedition} namespace: space, transit and the Moon;
 *   <li>every dimension a planet pack adds with Expedition's planet generator ({@code
 *       expedition:planet}), whatever its namespace.
 * </ul>
 *
 * <p>Any other extra dimension still makes the world experimental, as in vanilla.
 */
public final class StableDimensions {
    private StableDimensions() {}

    /**
     * Whether a dimension is one of Expedition's.
     *
     * @param key the dimension's key
     * @param stem the dimension
     * @return true if it is in Expedition's namespace or generated by Expedition's planet generator
     */
    public static boolean isExpeditions(ResourceKey<LevelStem> key, LevelStem stem) {
        return key.location().getNamespace().equals(ExpeditionMod.MOD_ID)
                || stem.generator() instanceof PlanetChunkGenerator;
    }
}
